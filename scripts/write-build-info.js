// Generates src/lib/build-info.gen.ts (commit, version, build time) shown in
// the Settings footer and included in diagnostics exports. Runs as part of
// `npm run build`. The product version is the companion's version.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

function gitCommit() {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: new URL('..', import.meta.url).pathname }).toString().trim();
  } catch {
    return 'unknown';
  }
}

let version = '0.0.0';
try {
  const companion = JSON.parse(readFileSync(new URL('../companion/package.json', import.meta.url), 'utf8'));
  version = companion.version || version;
} catch { /* keep fallback */ }

const commit = gitCommit();
const builtAt = new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC';

const out = `// AUTO-GENERATED by scripts/write-build-info.js — do not edit.
export const BUILD_INFO = {
  commit: ${JSON.stringify(commit)},
  version: ${JSON.stringify(version)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;
`;
writeFileSync(new URL('../src/lib/build-info.gen.ts', import.meta.url), out);
console.log(`build-info: commit=${commit} version=${version} builtAt=${builtAt}`);
